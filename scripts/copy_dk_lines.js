/*
"Copy DK lines" bookmarklet.

Open DraftKings' TT Elite Series page (sportsbook.draftkings.com/leagues/tabletennis/tt-elite-series) in your own
browser, click the bookmark, and every match's moneyline is copied to the clipboard as

    Oskar Jadach -150 / Wojciech Urban +120

one match per line - exactly what the app's "Paste DraftKings lines" box accepts. It reads the page you are
looking at, so it works wherever the page works (DraftKings blocks scripts and servers, not your browser).

Setup (Safari, Chrome, Firefox): make any bookmark, then edit it and replace its address with the ONE-LINE
version below (everything from "javascript:" to the end). The one-line version is generated by
scripts/make_bookmarklet.py and printed in DEPLOY.md.
*/
(function () {
  const clean = s => (s || "").replace(/\s+/g, " ").trim();
  const isOdds = s => /^[+−-]\d{3,4}$/.test(clean(s).replace("−", "-"));
  const rows = Array.from(document.querySelectorAll("tr"));
  const parts = [];
  const heads = Array.from(document.querySelectorAll("th")).map(th => clean(th.innerText).toLowerCase());
  let mlCol = heads.findIndex(h => h.includes("moneyline") || h === "winner" || h.includes("match winner"));
  for (const tr of rows) {
    const nameEl = tr.querySelector('[class*="event-cell__name"], [class*="participant"], [class*="team-name"]');
    const name = clean(nameEl ? nameEl.innerText : "");
    if (!name) continue;
    const oddsEls = Array.from(tr.querySelectorAll('[class*="sportsbook-odds"], [class*="odds"]')).map(e => clean(e.innerText)).filter(isOdds);
    if (!oddsEls.length) continue;
    const tds = Array.from(tr.querySelectorAll("td"));
    let odds = null;
    if (mlCol >= 0 && tds[mlCol]) {
      const o = Array.from(tds[mlCol].querySelectorAll("*")).map(e => clean(e.innerText)).find(isOdds);
      if (o) odds = o;
    }
    if (!odds) odds = oddsEls[oddsEls.length - 1];
    parts.push({ name, odds: odds.replace("−", "-") });
  }
  if (parts.length < 2) {
    const names = Array.from(document.querySelectorAll('[class*="event-cell__name"]')).map(e => clean(e.innerText));
    const odds = Array.from(document.querySelectorAll('[class*="sportsbook-odds"]')).map(e => clean(e.innerText)).filter(isOdds);
    if (names.length && odds.length >= names.length) {
      const step = Math.round(odds.length / names.length);
      names.forEach((n, i) => parts.push({ name: n, odds: odds[i * step + step - 1].replace("−", "-") }));
    }
  }
  const lines = [];
  for (let i = 0; i + 1 < parts.length; i += 2) lines.push(`${parts[i].name} ${parts[i].odds} / ${parts[i + 1].name} ${parts[i + 1].odds}`);
  const text = lines.join("\n");
  if (!lines.length) { alert("No lines found on this page. Make sure the TT Elite Series moneyline table is showing."); return; }
  const done = () => alert(`Copied ${lines.length} matches:\n\n${lines.slice(0, 6).join("\n")}${lines.length > 6 ? "\n..." : ""}`);
  if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(text).then(done, () => { prompt("Copy these lines:", text); });
  else prompt("Copy these lines:", text);
})();
